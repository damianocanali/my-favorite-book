// Regenerates lib/print/fontFaces.js from public/fonts: the print/PDF HTML
// embeds the fonts as data: URIs so the headless renderer never fetches a
// font from anywhere (review §7 items 18–19). Run after changing a font:
//   node scripts/build-print-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const css = readFileSync('public/fonts/fonts.css', 'utf8')
const faces = css.match(/@font-face \{[\s\S]*?\}/g)
  .filter((f) => /'(Fredoka|Nunito)'/.test(f))
  .map((f) => f.replace(/url\('\/fonts\/([^']+)'\)/, (_m, file) =>
    `url(data:font/woff2;base64,${readFileSync(`public/fonts/${file}`).toString('base64')})`))
  .join('\n')

writeFileSync('lib/print/fontFaces.js', `// GENERATED by scripts/build-print-fonts.mjs from public/fonts — do not edit.
// Fredoka + Nunito (SIL OFL) as data: URIs for the print HTML, so PDF
// rendering loads no font from a third party (or from anywhere).
export const PRINT_FONT_FACES = ${JSON.stringify(faces)}
export const PRINT_FONT_STYLE = \`<style>\${PRINT_FONT_FACES}</style>\`
`)
console.log('wrote lib/print/fontFaces.js', faces.length, 'chars')
