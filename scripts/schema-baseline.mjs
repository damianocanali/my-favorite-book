// Builds supabase/schema-baseline.sql: the dashboard-created tables
// (supabase/dashboard-tables.sql, reconstructed) followed by every
// migration in apply order. Each migration is idempotent, so this file
// replays to the schema the repo believes production has.
//
// It is a STOPGAP until the owner commits a real
//   supabase db dump --schema-only > supabase/schema.sql
// Re-run after adding a migration:  node scripts/schema-baseline.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const dir = 'supabase-migrations'
const files = readdirSync(dir).filter((f) => /^\d{3}_.*\.sql$/.test(f)).sort()
const parts = [
  `-- GENERATED by scripts/schema-baseline.mjs — do not edit by hand.
-- Schema baseline for My Book Lab (privacy review §7 item 24).
--
-- Part 1: tables created in the Supabase dashboard, RECONSTRUCTED from code.
-- Part 2: supabase-migrations/*.sql in apply order (${files[0]} … ${files.at(-1)}).
--
-- TO BE REPLACED by a real \`supabase db dump --schema-only\` (owner action).
-- tests/rls-baseline.test.js fails if any table created here lacks
-- "enable row level security".
`,
  readFileSync('supabase/dashboard-tables.sql', 'utf8'),
  ...files.map((f) => `\n-- ════════ ${dir}/${f} ════════\n${readFileSync(`${dir}/${f}`, 'utf8')}`),
]
writeFileSync('supabase/schema-baseline.sql', parts.join('\n'))
console.log(`wrote supabase/schema-baseline.sql (${files.length} migrations)`)
